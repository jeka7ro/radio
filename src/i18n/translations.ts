export type TranslationSchema = typeof translations.ro;

export function formatTranslation(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return Object.entries(params).reduce(
    (acc, [key, val]) => acc.replace(new RegExp(`\\{\\{${key}\\}\\}`, 'g'), String(val)),
    template
  );
}

export function detectInitialLanguage(): LanguageCode {
  if (typeof navigator === 'undefined') return 'ro';
  const langs = navigator.languages ? [...navigator.languages] : [navigator.language];
  for (const l of langs) {
    if (!l) continue;
    const lower = l.toLowerCase();
    if (lower.startsWith('ro')) return 'ro';
    if (lower.startsWith('en')) return 'en';
  }
  return 'ro';
}

